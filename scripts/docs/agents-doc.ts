// Generates docs/AGENTS.md from the agent tool catalog. `--check` fails if the file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tools, jsonSchema, GROUP_LABELS, capabilities, type ToolDef } from '../../packages/agent/src/index';
import { COMMAND_COVERAGE } from '../../packages/agent/src/coverage';
import { PROMPTS, RESOURCES } from '../../apps/desktop/src/main/mcp/guide';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = join(root, 'docs', 'AGENTS.md');

type Prop = { type?: string | string[]; enum?: unknown[]; description?: string; anyOf?: Prop[]; items?: Prop; minimum?: number; maximum?: number; const?: unknown };
function typeOf(p: Prop): string {
  if (p.enum) return p.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (p.const !== undefined) return JSON.stringify(p.const);
  if (p.anyOf) return p.anyOf.map(typeOf).join(' or ');
  if (p.type === 'array') return `${p.items ? typeOf(p.items) : 'any'}[]`;
  const range = p.minimum != null && p.maximum != null ? ` (${p.minimum} to ${p.maximum})` : p.minimum != null ? ` (at least ${p.minimum})` : p.maximum != null ? ` (at most ${p.maximum})` : '';
  return `${Array.isArray(p.type) ? p.type.join(' or ') : p.type ?? 'any'}${range}`;
}
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function toolSection(t: ToolDef): string {
  const schema = jsonSchema(t) as { properties?: Record<string, Prop>; required?: string[] };
  const req = new Set(schema.required ?? []);
  const rows = Object.entries(schema.properties ?? {}).map(([k, p]) => `| \`${k}\` | ${cell(typeOf(p))} | ${req.has(k) ? 'yes' : ''} | ${cell(p.description ?? '')} |`);
  const changes = t.access === 'edit' ? 'Changes the project (one undo step; asks first in Ask mode).' : t.mutates ? 'Acts in the app or writes files (asks first in Ask mode).' : 'Reads only; never asks.';
  return [
    `### \`${t.name}\`: ${t.title}`,
    '',
    t.description,
    '',
    `*${changes}*`,
    '',
    ...(rows.length ? ['| Argument | Type | Required | Notes |', '|---|---|---|---|', ...rows, ''] : ['No arguments.', '']),
    ...t.examples.map((e) => `Example${e.note ? ` (${e.note})` : ''}: \`${JSON.stringify(e.args)}\``),
    '',
  ].join('\n');
}

export function render(): string {
  const all = [...tools().values()];
  const caps = capabilities() as Record<string, unknown> & { effects: Array<{ type: string; label: string; description: string; addable: boolean; params: Array<{ key: string; min: number; max: number; default: number | null; unit: string | null; description: string }> }>; transitions: Array<{ id: string; description: string }>; textAnimations: Array<{ id: string; description: string }>; captionStyles: Array<{ id: string; label: string }>; exportPresets: Array<{ id: string; label: string }>; speedRamps: Array<{ id: string; label: string }> };
  const groups = new Map<string, ToolDef[]>();
  for (const t of all) { const g = GROUP_LABELS[t.group]; (groups.get(g) ?? groups.set(g, []).get(g)!).push(t); }
  const uiOnly = Object.entries(COMMAND_COVERAGE).filter(([, c]) => 'uiOnly' in c) as Array<[string, { uiOnly: string }]>;
  return [
    '# Director for AI agents',
    '',
    '<!-- Generated by scripts/docs/agents-doc.ts from the tool catalog. Do not edit by hand: run `npx tsx scripts/docs/agents-doc.ts`. -->',
    '',
    `Director exposes every editing operation as a tool an AI assistant can call: ${all.length} tools, from reading the timeline to cutting, grading, captioning, mixing and exporting. The same catalog is served over MCP (HTTP and stdio) and plain HTTP, and the app runs every call against the project open in its window, so the person sees each change as it happens.`,
    '',
    '## Connect',
    '',
    'In Director open Settings (Cmd+,), turn on **Connect an AI**, and copy the setup for your app:',
    '',
    '- **Claude Code**: one command, `claude mcp add --transport http director http://127.0.0.1:47615/mcp --header "Authorization: Bearer <token>"`.',
    '- **Claude Desktop**: a JSON entry for Settings, Developer, Edit Config. It launches the bridge bundled with Director (`mcp-stdio.cjs`, run by the Director binary in Node mode), which forwards to the running app.',
    '- **Other MCP apps**: an HTTP server entry with the URL and an `Authorization: Bearer` header.',
    '- **Any AI over HTTP**: `GET /api/tools?format=anthropic|openai|mcp` returns the tool definitions; `POST /api/tools/<name>` with a JSON body runs one and returns `{ ok, data }` or `{ ok: false, error: { code, message, hint } }`. Send `X-Director-Client: <your name>` to label your changes.',
    '',
    'Settings shows the exact snippet with your token. The token is private: anyone with it on this Mac can edit your projects. New token disconnects every app.',
    '',
    '## The assistant inside Director',
    '',
    'Director also has its own chat: the **Assistant** panel in the Edit workspace (Cmd+J). Type what you want in your own words and Claude works through it with this same catalog, using your API key from Settings. It needs no connection setup, follows the same Ask and Auto modes, and labels its changes "Assistant" so the Agent panel can revert them.',
    '',
    'Inside the app only text reaches Anthropic: your messages, the transcript and what the tools report. File paths are replaced with `[path]`, media file names lose their extension, and the tools that return pictures or need file paths (`render_frame`, `render_contact_sheet`, `import_media`) are left out. An assistant connected over MCP runs on your side of the connection, so it can use every tool.',
    '',
    '## Safety',
    '',
    '- Listens on 127.0.0.1 only, needs the bearer token, refuses browser origins and foreign Host headers.',
    '- **Ask mode** (default): every change waits for the person to click Accept in Director; reads never ask. **Auto mode**: changes apply at once. In both, every change is one undo step labelled with the assistant\'s name, and the Agent panel lists everything and can revert all agent changes in one step while keeping the person\'s own edits.',
    '- `propose_edits` always asks, whatever the mode.',
    '- No tool deletes files. Exports are written only inside the export folder, never over an existing file. Imports accept existing media files only.',
    '',
    '## How to work',
    '',
    '- Start with `get_started`, then `get_timeline` and `get_transcript`.',
    '- Times are **seconds** on the timeline (edit positions snap to the nearest frame). Positions are project pixels from the frame center (+x right, +y down). Volume is dB. Ids come from read tools and change when clips are split or re-created, so read again after structural edits.',
    '- Every edit tool accepts `dryRun` (preview what would change) and `expectRevision` (refuse if the project changed since you read it; every read returns `revision`).',
    '- `batch` runs several edit tools as one atomic step and one approval. If a step fails, nothing changes and the error names the step.',
    '- See your work with `render_contact_sheet` (a grid of frames) and `render_frame`.',
    '- Errors say what went wrong and how to fix it (often naming the tool to call).',
    '',
    '## MCP resources and prompts',
    '',
    ...RESOURCES.map((r) => `- Resource \`${r.uri}\`: ${r.description}.`),
    ...PROMPTS.map((p) => `- Prompt \`${p.name}\` (${p.title}): ${p.description}.${p.arguments.length ? ` Arguments: ${p.arguments.map((a) => `\`${a.name}\``).join(', ')}.` : ''}`),
    '',
    '## Creative vocabulary',
    '',
    '| Effect | Parameters (range, unit) |',
    '|---|---|',
    ...caps.effects.filter((e) => e.addable).map((e) => `| \`${e.type}\` ${e.label} | ${cell(e.params.map((p) => `\`${p.key}\` ${p.min} to ${p.max}${p.unit ? ` ${p.unit}` : ''}${p.default != null ? `, default ${p.default}` : ''}`).join('; ') || 'see extras')} |`),
    '',
    `Transitions: ${caps.transitions.map((t) => `\`${t.id}\``).join(', ')}. Text animations: ${caps.textAnimations.map((t) => `\`${t.id}\``).join(', ')}. Caption styles: ${caps.captionStyles.map((c) => `\`${c.id}\``).join(', ')}. Speed ramps: ${caps.speedRamps.map((r) => `\`${r.id}\``).join(', ')}. Export presets: ${caps.exportPresets.map((p) => `\`${p.id}\``).join(', ')}.`,
    '',
    '## Tools',
    '',
    ...[...groups.entries()].map(([g, ts]) => `- **${g}**: ${ts.map((t) => `\`${t.name}\``).join(', ')}`),
    '',
    ...[...groups.entries()].flatMap(([g, ts]) => [`## ${g}`, '', ...ts.map(toolSection)]),
    '## What stays with the person',
    '',
    'Every command in the app is reachable by a tool except these, on purpose:',
    '',
    ...uiOnly.map(([id, c]) => `- \`${id}\`: ${c.uiOnly}.`),
    '',
  ].join('\n');
}

const text = render();
if (process.argv.includes('--check')) {
  const cur = readFileSync(out, 'utf8');
  if (cur !== text) { console.error('docs/AGENTS.md is out of date: run npx tsx scripts/docs/agents-doc.ts'); process.exit(1); }
  console.log(`AGENTS.md is current (${tools().size} tools, ${text.length} chars)`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${tools().size} tools)`);
}
