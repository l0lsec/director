import { sh, assert, tmp, groundTruth, root } from '../lib.mjs';
import { createHash } from 'node:crypto';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const sha = (p) => createHash('sha256').update(readFileSync(p)).digest('hex');

export default async function () {
  const gt = groundTruth();
  const names = Object.keys(gt.checksums);
  assert(names.length >= 10, `ground truth lists ${names.length} fixtures`);
  // Fresh, independent generation into an empty directory; must match the committed checksums byte for byte.
  const dir = tmp('fixtures-regen');
  sh('node', [join(root, 'scripts/fixtures/make-fixtures.mjs'), '--force'], { env: { DIRECTOR_FIXTURES_OUT: dir }, timeout: 900_000 });
  const mismatches = [];
  for (const n of names) {
    const p = join(dir, n);
    if (!existsSync(p)) { mismatches.push(`${n}: not generated`); continue; }
    const s = sha(p);
    if (s !== gt.checksums[n]) mismatches.push(`${n}: ${s.slice(0, 12)} != ${gt.checksums[n].slice(0, 12)}`);
  }
  assert(mismatches.length === 0, `non-deterministic fixtures:\n${mismatches.join('\n')}`);
  // Sanity: the sync fixture really has 300 frames at 30 fps.
  const probe = JSON.parse(sh('ffprobe', ['-v', 'error', '-count_frames', '-select_streams', 'v:0', '-show_entries', 'stream=nb_read_frames,r_frame_rate,width,height', '-of', 'json', join(dir, 'sync-1080p30.mp4')]).stdout).streams[0];
  assert(Number(probe.nb_read_frames) === 300 && probe.r_frame_rate === '30/1' && probe.width === 1920, `sync fixture probe ${JSON.stringify(probe)}`);
  return `${names.length} fixtures regenerated byte-identical`;
}
